"""
Prefix bank evaluation for distributional alignment analysis (PDF §3 step 5).

Prefix banks (PDF §3 "Fixed prefix banks"):
  - teacher:               produced by setup_data.py --prefix-banks  [SUPPLIED]
  - original_draft:        produced by setup_data.py --prefix-banks  [SUPPLIED]
  - exact_spec_original:   MUST be generated by our own speculative sampler
                           using the ORIGINAL (undistilled) student at gamma=4.
                           NOT produced by the dataset repo.
  - trained_student_{off,on}_seed{N}: generated by evaluating each trained
                           student's OWN policy on the shared prompt set.

IMPORTANT: Banks (teacher) and (exact_spec_original) are distributional consistency
controls — at matched prompts and sampling settings they sample the same target-prefix
law.  A systematic gap suggests an implementation or evaluation problem.

Metrics computed at each saved prefix position:
  - Forward KL:       KL(p_T(·|h) || q(·|h))
  - Reverse KL:       KL(q(·|h) || p_T(·|h))
  - Total Variation:  TV(p_T, q) = 0.5 * sum |p_T - q|
  - Expected one-token acceptance: 1 - TV(p_T, q) = sum_x min(p_T(x), q(x))
  - Greedy agreement: int(argmax(p_T) == argmax(q))
"""

import gzip
import json
from pathlib import Path
from typing import Dict, List, Optional

import torch
import torch.nn.functional as F


EPS = 1e-10


def _load_bank(path: str) -> List[dict]:
    p = Path(path)
    opener = gzip.open if p.suffix == ".gz" else open
    with opener(p, "rt", encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


@torch.no_grad()
def evaluate_prefix_bank(
    teacher_model,
    draft_model,
    tokenizer,
    bank_records: List[dict],
    device: str,
    dtype=torch.float16,
) -> List[dict]:
    """
    Evaluate distributional alignment metrics for a list of prefix bank records.

    Each record (from the locked JSONL) has fields:
      prompt_id, bank, position, prompt, response_prefix_token_ids

    Returns list of dicts, one per record, with computed alignment metrics.
    """
    teacher_model.eval()
    draft_model.eval()
    results = []

    for rec in bank_records:
        prompt_text = rec["prompt"]
        prefix_ids = rec["response_prefix_token_ids"]

        prompt_enc = tokenizer(prompt_text, return_tensors="pt")["input_ids"].to(device)
        full_ids = torch.cat([
            prompt_enc,
            torch.tensor([prefix_ids], dtype=torch.long, device=device)
        ], dim=1)  # (1, prompt_len + prefix_len)

        # Teacher distribution at the last prefix position.
        with torch.autocast(device_type=device.split(":")[0], dtype=dtype):
            t_out = teacher_model(full_ids)
        p_t = F.softmax(t_out.logits[0, -1, :].float(), dim=-1)

        # Draft distribution at the same position.
        with torch.autocast(device_type=device.split(":")[0], dtype=dtype):
            d_out = draft_model(full_ids)
        q = F.softmax(d_out.logits[0, -1, :].float(), dim=-1)

        metrics = compute_alignment_metrics(p_t, q)
        results.append({
            "prompt_id": rec.get("prompt_id", ""),
            "bank": rec.get("bank", ""),
            "position": rec.get("position", -1),
            **metrics,
        })

    return results


def compute_alignment_metrics(p: torch.Tensor, q: torch.Tensor) -> dict:
    """
    Compute all alignment metrics between target distribution p and draft q.
    Both are (V,) probability vectors.
    """
    p = p.float()
    q = q.float()

    # Forward KL: KL(p || q)
    fwd_kl = (p * (torch.log(p + EPS) - torch.log(q + EPS))).sum().item()

    # Reverse KL: KL(q || p)
    rev_kl = (q * (torch.log(q + EPS) - torch.log(p + EPS))).sum().item()

    # TV distance.
    tv = 0.5 * (p - q).abs().sum().item()

    # Expected one-token acceptance (= 1 - TV).
    expected_accept = torch.minimum(p, q).sum().item()

    # Greedy agreement.
    greedy_agree = int(p.argmax().item() == q.argmax().item())

    return {
        "fwd_kl": fwd_kl,
        "rev_kl": rev_kl,
        "tv": tv,
        "expected_accept": expected_accept,
        "greedy_agree": greedy_agree,
    }


def generate_exact_spec_bank(
    draft_model,
    target_model,
    tokenizer,
    prompt_records: List[dict],
    saved_prefix_positions: List[int],
    gamma: int = 4,
    device: str = "cuda",
    seed: int = 6304,
    output_path: str = "data/prefix_banks/exact_spec_bank.jsonl.gz",
) -> str:
    """
    Generate the exact-speculative prefix bank using our own sampler.
    This bank is NOT produced by setup_data.py --prefix-banks; it must be
    built by the student's correct exact speculative sampler.

    Records positions 1..64 (stratified into bins [1,16],[17,32],[33,64])
    and 65..192 for each prompt.

    Returns path to the written file.
    """
    from .speculative import exact_speculative_generate, QWEN_EOS_IDS

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    records = []

    for rec in prompt_records:
        prompt_text = rec["prompt"] if "prompt" in rec else rec["text"]
        prompt_ids = tokenizer(prompt_text, return_tensors="pt")["input_ids"].to(device)
        torch.manual_seed(seed + rec.get("order", 0))

        generated, _ = exact_speculative_generate(
            draft_model, target_model, prompt_ids,
            max_new_tokens=max(saved_prefix_positions),
            gamma=gamma, temperature=1.0,
            eos_ids=QWEN_EOS_IDS, device=device,
        )

        for pos in saved_prefix_positions:
            if pos <= len(generated):
                records.append({
                    "prompt_id": rec.get("id", rec.get("order", "")),
                    "bank": "exact_spec_original_gamma4",
                    "position": pos,
                    "prompt": prompt_text,
                    "response_prefix_token_ids": generated[:pos],
                })

    import gzip
    with gzip.open(output_path, "wt", encoding="utf-8") as fh:
        for r in records:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    return output_path
